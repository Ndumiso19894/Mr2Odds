const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const store = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
const document = { documentElement: { dataset: {} }, addEventListener: () => {}, querySelector: () => null, querySelectorAll: () => [] };
const ctx = { window: {}, document, localStorage: store, navigator: { onLine: true }, URL, console, setTimeout, clearTimeout, AbortController };
vm.createContext(ctx);
const root = 'android/app/src/main/assets/www/';
vm.runInContext(fs.readFileSync(root + 'core.js', 'utf8'), ctx);
let slip = fs.readFileSync(root + 'slip.js', 'utf8').replace('  function legLive(l, sc) {', '  PR.testSettleLeg = settleLeg;\n  function legLive(l, sc) {');
vm.runInContext(slip, ctx);
const PR = ctx.window.PR;
const leg = sel => ({sel, sport:'soccer'});
const score = {ft:true, hg:1, ag:0, hc:5, ac:0, hcards:2, acards:0};
assert.equal(PR.testSettleLeg(leg('CHO35'), score), 'won');
assert.equal(PR.testSettleLeg(leg('CAO35'), score), 'lost');
assert.equal(PR.testSettleLeg(leg('CO95'), score), 'lost');
assert.equal(PR.testSettleLeg(leg('KHO15'), score), 'pending');
assert.equal(PR.testSettleLeg(leg('KAO15'), score), 'pending');
assert.equal(PR.testSettleLeg(leg('CHO40'), score), 'won');
assert.equal(PR.testSettleLeg(leg('CHO50'), score), 'void');
assert.equal(PR.testSettleLeg(leg('CHO35'), {...score, ac:null}), 'won');
assert.equal(PR.testSettleLeg(leg('CO95'), {...score, ac:null}), 'pending');
assert.equal(PR.testSettleLeg(leg('KAO15'), {...score, acards:null}), 'pending');
for (const c of JSON.parse(fs.readFileSync('tests/recommendation_cases.json'))) assert.equal(!PR.isDropped(c.sel), c.allowed, c.sel);
for (const sel of ['1X', 'HO05', 'U25', 'KO35', 'O05']) assert.equal(PR.addBtn('f', sel, 1.3), '', sel);
assert.equal(PR.addBtn('f', 'O15', 1.15), '');
assert.match(PR.addBtn('f', 'O15', 1.16), /data-add-fx/);
console.log('Team market settlement and eligibility UI tests passed');
